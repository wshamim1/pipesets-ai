"""
labdb_benchmark.py — a small, fully known dataset for Evaluate → Optimize models.

    python scripts/benchmarks/labdb_benchmark.py sql > labdb_seed.sql      # tables + rows for MySQL `labdb`
    python scripts/benchmarks/labdb_benchmark.py setup --tenant T --project P --user U \\
        --connection-from APP_ID                                            # pipelines + datasets

Every expected answer is computed from the same rows the SQL inserts, so a case can only pass if
the pipeline really queried the database. Fact cases expect a single value (a name, a region, a
whole number under 1000, so no thousands separator), which the Contains scorer can check; the five
refusal cases describe the right behaviour and need the LLM Judge scorer.

``setup`` runs the backend's own API in-process against the configured database (header auth, as
the tests do) and creates, by name, skipping what exists:

* "labdb SQL agent" — published: one LLM node + the read-only SQL tool + the MySQL connection node
  copied from ``--connection-from`` (an app that already has it, e.g. pg-test).
* "Sales analyst crew" — draft: a sequential Master Agent that plans, calls the SQL agent pipeline
  for the data, then a writer child for the answer. Three model slots, one in a nested pipeline.
* Datasets "labdb facts — SQL agent" and "labdb facts — crew", the same 25 cases, one per pipeline.
"""

