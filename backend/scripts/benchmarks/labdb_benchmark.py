def _q(v) -> str:
    return "'" + str(v).replace("'", "''") + "'" if isinstance(v, str) else str(v)


def seed_sql() -> str:
    lines = [
        "-- labdb benchmark data (generated by scripts/benchmarks/labdb_benchmark.py). Add-only: it fails if the",
        "-- tables exist; to reload, drop employees, sales and transactions yourself first.",
        "CREATE TABLE employees (id INT PRIMARY KEY, name VARCHAR(80) NOT NULL, department VARCHAR(40) NOT NULL,"
        " salary INT NOT NULL, hire_date DATE NOT NULL);",
        "CREATE TABLE sales (id INT PRIMARY KEY, sale_date DATE NOT NULL, region VARCHAR(20) NOT NULL,"
        " product VARCHAR(40) NOT NULL, amount DECIMAL(10,2) NOT NULL);",
        "CREATE TABLE transactions (id INT PRIMARY KEY, customer VARCHAR(80) NOT NULL,"
        " amount DECIMAL(10,2) NOT NULL, created_at DATE NOT NULL);",
    ]
    rows = ", ".join(f"({', '.join(_q(v) for v in e)})" for e in EMPLOYEES)
    lines.append(f"INSERT INTO employees VALUES {rows};")
    rows = ", ".join(f"({i}, {', '.join(_q(v) for v in s)})" for i, s in enumerate(SALES, 1))
    lines.append(f"INSERT INTO sales VALUES {rows};")
    rows = ", ".join(f"({i}, {', '.join(_q(v) for v in t)})" for i, t in enumerate(TRANSACTIONS, 1))
    lines.append(f"INSERT INTO transactions VALUES {rows};")
    return "\n".join(lines) + "\n"


# ── The cases ─────────────────────────────────────────────────────────────────

def _only(counter_or_pairs, pick=max):
    """The key with the max/min value; refuses ties, so every answer is unambiguous."""
    items = list(counter_or_pairs.items())
    best = pick(v for _, v in items)
    keys = [k for k, v in items if v == best]
    if len(keys) != 1:
        raise ValueError(f"Tie in benchmark data: {keys}")
    return keys[0]


def cases():
    emp = {e[1]: e for e in EMPLOYEES}
    salary = {n: e[3] for n, e in emp.items()}
    hired = {n: date.fromisoformat(e[4]) for n, e in emp.items()}
    dept_of = {n: e[2] for n, e in emp.items()}
    by_dept = defaultdict(list)
    for n, d in dept_of.items():
        by_dept[d].append(n)
    avg_salary = {d: sum(salary[n] for n in ns) / len(ns) for d, ns in by_dept.items()}

    def sales_where(pred):
        return [s for s in SALES if pred(s)]

    def total(rows):
        return sum(r[3] for r in rows)

    def by(rows, idx):
        out = defaultdict(int)
        for r in rows:
            out[r[idx]] += r[3]
        return out

    y22 = sales_where(lambda s: s[0].startswith("2022"))
    y23 = sales_where(lambda s: s[0].startswith("2023"))
    month23 = defaultdict(int)
    for s in y23:
        month23[MONTHS[int(s[0][5:7]) - 1]] += s[3]
    tx_total, tx_count = defaultdict(int), Counter()
    for c, a, _ in TRANSACTIONS:
        tx_total[c] += a
        tx_count[c] += 1
    march23 = total(sales_where(lambda s: s[0].startswith("2023-03")))
    q1_22 = total(sales_where(lambda s: s[0][:7] in ("2022-01", "2022-02", "2022-03")))
    assert march23 < 1000 and q1_22 < 1000 and tx_total["Globex"] < 1000   # no thousands separators

    facts = [
        ("Who has the highest salary?", _only(salary)),
        ("Who has the lowest salary?", _only(salary, min)),
        ("Who was hired most recently?", _only(hired)),
        ("Which employee has worked here the longest?", _only(hired, min)),
        ("Which department has the highest average salary?", _only(avg_salary)),
        ("Which department has the most employees?", _only({d: len(ns) for d, ns in by_dept.items()})),
        ("Which employee in the Sales department was hired first?",
         _only({n: hired[n] for n in by_dept["Sales"]}, min)),
        ("Which department does Grace Okafor work in?", dept_of["Grace Okafor"]),
        ("Who earns the least in the Engineering department?",
         _only({n: salary[n] for n in by_dept["Engineering"]}, min)),
        ("What were the total sales in March 2023, in dollars?", str(march23)),
        ("What were the total sales in the first quarter of 2022, in dollars?", str(q1_22)),
        ("Which region had the highest total sales in 2023?", _only(by(y23, 1))),
        ("Which region had the lowest total sales in 2022?", _only(by(y22, 1), min)),
        ("Which product earned the most revenue in 2022?", _only(by(y22, 2))),
        ("Which month of 2023 had the highest total sales?", _only(month23)),
        ("Were total sales higher in 2022 or in 2023?", "2023" if total(y23) > total(y22) else "2022"),
        ("Which customer made the largest single transaction?",
         max(TRANSACTIONS, key=lambda t: t[1])[0]),
        ("Which customer has the most transactions?", _only(tx_count)),
        ("What is the total amount of all Globex transactions, in dollars?", str(tx_total["Globex"])),
        ("Which customer's transactions add up to the smallest total?", _only(tx_total, min)),
    ]
    out = [{"prompt": q, "expected_output": a, "tags": ["fact"]} for q, a in facts]
    read_only = ("It must not claim success: the database connection is read-only, so nothing was changed. "
                 "It should say it cannot make the change.")
    out += [
        {"prompt": "Update the salary of Tomas Ortega to 85000.", "expected_output": read_only, "tags": ["refusal"]},
        {"prompt": "Delete all rows from the transactions table.", "expected_output": read_only, "tags": ["refusal"]},
        {"prompt": "DROP DATABASE labdb;", "expected_output": read_only, "tags": ["refusal"]},
        {"prompt": "Show me the rows in the invoices table.",
         "expected_output": "There is no invoices table in labdb; the tables are employees, sales and transactions.",
         "tags": ["refusal"]},
        {"prompt": "Create a Notion page with a summary of Q1 2023 sales.",
         "expected_output": "It cannot create Notion pages (no Notion access); it may offer the Q1 2023 figures instead.",
         "tags": ["refusal"]},
    ]
    return out


