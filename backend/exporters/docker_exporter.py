"""Docker Compose exporter — generates a docker-compose.yml deployment stub."""

from typing import Dict

import yaml

from exporters.helpers import nodes_by_type, edge_map, collect_env_vars


def to_docker_compose(app: Dict) -> str:
    flow  = app["flow_data"]
    nodes = nodes_by_type(flow)
    adj   = edge_map(flow)
    slug  = app["name"].lower().replace(" ", "-")

    llm_cfg  = nodes["llm"][0].get("data", {}) if nodes["llm"] else {}
    provider = llm_cfg.get("provider", "openai")

    env_vars: Dict[str, str] = {
        "PIPESETS_APP_NAME": app["name"],
        "DEFAULT_LLM_PROVIDER": provider,
        "DEFAULT_LLM_MODEL": llm_cfg.get("model", "gpt-4o"),
        "DEFAULT_LLM_TEMPERATURE": str(llm_cfg.get("temperature", 0.7)),
        "DEFAULT_LLM_MAX_TOKENS": str(llm_cfg.get("max_tokens", 1024)),
    }

    for k in collect_env_vars(provider, nodes, adj):
        if k not in env_vars:
            env_vars[k] = f"${{{k}}}"

    for conn_node in nodes["connection"]:
        d          = conn_node.get("data", {})
        cfg        = d.get("config", {})
        ct         = d.get("connection_type", d.get("type", "")).lower()
        label_slug = d.get("label", "db").upper().replace(" ", "_")
        if ct in ("postgres", "postgresql"):
            env_vars[f"DB_{label_slug}_HOST"]     = cfg.get("host", "localhost")
            env_vars[f"DB_{label_slug}_PORT"]     = str(cfg.get("port", 5432))
            env_vars[f"DB_{label_slug}_NAME"]     = cfg.get("database", "")
            env_vars[f"DB_{label_slug}_USER"]     = cfg.get("user", "")
            env_vars[f"DB_{label_slug}_PASSWORD"] = f"${{{label_slug}_PASSWORD}}"

    compose = {
        "version": "3.9",
        "services": {
            "backend": {
                "image": "python:3.11-slim",
                "working_dir": "/app",
                "volumes": ["./backend:/app"],
                "command": "pip install -r requirements.txt && uvicorn main:app --host 0.0.0.0 --port 8000",
                "ports": ["8000:8000"],
                "environment": env_vars,
                "restart": "unless-stopped",
            },
            "frontend": {
                "image": "node:20-alpine",
                "working_dir": "/app",
                "volumes": ["./frontend:/app"],
                "command": "npm install && npm run preview -- --host 0.0.0.0 --port 5173",
                "ports": ["5173:5173"],
                "depends_on": ["backend"],
                "restart": "unless-stopped",
            },
        },
    }
    return (
        f"# docker-compose.yml — {app['name']}\n"
        f"# Generated by Pipesets AI\n\n"
        + yaml.dump(compose, sort_keys=False, allow_unicode=True)
    )
