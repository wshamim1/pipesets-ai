"""CrewAI exporter — generates a ready-to-run CrewAI multi-agent script."""

import json
from typing import Dict, List

from exporters.helpers import (
    nodes_by_type, edge_map, find_connection_for_tool,
    safe_fn, safe_class, provider_env_var, collect_env_vars, pip_packages,
)
from exporters.tool_bodies import tool_body_crewai


def to_crewai(app: Dict) -> str:
    flow       = app["flow_data"]
    nodes      = nodes_by_type(flow)
    adj        = edge_map(flow)
    app_name   = app["name"]
    app_desc   = app.get("description", "")

    llm_cfg       = nodes["llm"][0].get("data", {}) if nodes["llm"] else {}
    provider      = llm_cfg.get("provider", "openai")
    model         = llm_cfg.get("model", "gpt-4o")
    system_prompt = llm_cfg.get("system_prompt", "You are a helpful assistant.")
    api_key_val   = llm_cfg.get("api_key", "")
    env_key       = provider_env_var(provider)

    tool_blocks: List[str] = []
    tool_class_names: List[str] = []

    for node in nodes["tool"]:
        d    = node.get("data", {})
        tid  = d.get("toolId", "custom_tool")
        fn   = safe_fn(tid)
        cls  = safe_class(tid)
        desc = d.get("description", f"Tool: {d.get('label', tid)}")
        cfg  = d.get("config", {})
        conn = find_connection_for_tool(node, nodes, adj)
        tool_blocks.append(tool_body_crewai(cls, fn, tid, d.get("label", tid), desc, cfg, conn))
        tool_class_names.append(cls)

    for node in nodes["toolkit"]:
        for sub in node.get("data", {}).get("subTools", []):
            tid  = sub.get("toolId", "sub_tool")
            fn   = safe_fn(tid)
            cls  = safe_class(tid)
            desc = sub.get("description", f"Tool: {sub.get('label', tid)}")
            cfg  = sub.get("config", {})
            tool_blocks.append(tool_body_crewai(cls, fn, tid, sub.get("label", tid), desc, cfg, None))
            tool_class_names.append(cls)

    crew_llm        = f'"{provider}/{model}"'
    tools_instances = ", ".join(f"{n}()" for n in tool_class_names)

    env_vars = collect_env_vars(provider, nodes, adj)
    pip_pkgs = pip_packages(provider, nodes, "crewai")
    pip_line = f"# pip install {' '.join(sorted(set(pip_pkgs)))}"

    return "\n".join([
        '"""',
        f"  {app_name}",
        f"  {app_desc}",
        "  Generated by Pipesets AI",
        "",
        f"  {pip_line}",
        "",
        "  Environment variables:",
        *[f"    {k}=...  # {v}" for k, v in env_vars.items()],
        '"""',
        "",
        "import os",
        "from crewai import Agent, Task, Crew, Process",
        "from crewai.tools import BaseTool",
        "",
        f"os.environ.setdefault({json.dumps(env_key)}, {json.dumps(api_key_val)})",
        "",
        "# ── Custom Tools ──────────────────────────────────────────────────────────────",
        *[line for block in tool_blocks for line in block.splitlines()],
        "",
        "# ── Agents ───────────────────────────────────────────────────────────────────",
        "researcher = Agent(",
        '    role="Research Specialist",',
        '    goal="Gather accurate and relevant information for the task",',
        f'    backstory="""{system_prompt}""",',
        f"    llm={crew_llm},",
        f"    tools=[{tools_instances}],",
        "    verbose=True,",
        ")",
        "",
        "writer = Agent(",
        '    role="Content Writer",',
        '    goal="Synthesise gathered information into a clear, concise response",',
        '    backstory="Expert at summarising complex information.",',
        f"    llm={crew_llm},",
        "    verbose=True,",
        ")",
        "",
        "# ── Tasks ────────────────────────────────────────────────────────────────────",
        "research_task = Task(",
        '    description="Research the topic and gather all relevant facts.",',
        '    expected_output="A comprehensive bullet-point summary of findings.",',
        "    agent=researcher,",
        ")",
        "",
        "write_task = Task(",
        '    description="Write a clear response using the research findings.",',
        '    expected_output="A polished, user-facing answer.",',
        "    agent=writer,",
        ")",
        "",
        "# ── Crew ─────────────────────────────────────────────────────────────────────",
        "crew = Crew(",
        "    agents=[researcher, writer],",
        "    tasks=[research_task, write_task],",
        "    process=Process.sequential,",
        "    verbose=True,",
        ")",
        "",
        'if __name__ == "__main__":',
        '    result = crew.kickoff(inputs={"topic": "AI Agents"})',
        "    print(result)",
    ])
