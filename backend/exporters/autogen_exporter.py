"""AutoGen exporter — generates a ready-to-run Microsoft AutoGen script."""

import json
from typing import Dict, List

from exporters.helpers import (
    nodes_by_type, edge_map, find_connection_for_tool,
    safe_fn, provider_env_var, collect_env_vars, pip_packages,
)
from exporters.tool_bodies import tool_body_langchain


def to_autogen(app: Dict) -> str:
    flow       = app["flow_data"]
    nodes      = nodes_by_type(flow)
    adj        = edge_map(flow)
    app_name   = app["name"]
    app_desc   = app.get("description", "")

    llm_cfg       = nodes["llm"][0].get("data", {}) if nodes["llm"] else {}
    provider      = llm_cfg.get("provider", "openai")
    model         = llm_cfg.get("model", "gpt-4o")
    temperature   = llm_cfg.get("temperature", 0.7)
    max_tokens    = llm_cfg.get("max_tokens", 1024)
    system_prompt = llm_cfg.get("system_prompt", "You are a helpful assistant.")
    api_key_val   = llm_cfg.get("api_key", "")
    env_key       = provider_env_var(provider)

    tool_funcs: List[str] = []
    tool_registrations: List[str] = []

    for node in nodes["tool"]:
        d    = node.get("data", {})
        tid  = d.get("toolId", "custom_tool")
        fn   = safe_fn(tid)
        desc = d.get("description", f"Tool: {d.get('label', tid)}")
        cfg  = d.get("config", {})
        conn = find_connection_for_tool(node, nodes, adj)
        # AutoGen uses plain functions — strip @tool decorator
        raw  = tool_body_langchain(fn, tid, desc, cfg, conn)
        tool_funcs.append(raw.replace("@tool\n", ""))
        tool_registrations.append(
            f'register_function({fn}, caller=assistant, executor=user_proxy, '
            f'name="{fn}", description={json.dumps(desc)})'
        )

    for node in nodes["toolkit"]:
        for sub in node.get("data", {}).get("subTools", []):
            tid  = sub.get("toolId", "sub_tool")
            fn   = safe_fn(tid)
            desc = sub.get("description", f"Tool: {sub.get('label', tid)}")
            cfg  = sub.get("config", {})
            raw  = tool_body_langchain(fn, tid, desc, cfg, None)
            tool_funcs.append(raw.replace("@tool\n", ""))
            tool_registrations.append(
                f'register_function({fn}, caller=assistant, executor=user_proxy, '
                f'name="{fn}", description={json.dumps(desc)})'
            )

    env_vars = collect_env_vars(provider, nodes, adj)
    pip_pkgs = pip_packages(provider, nodes, "autogen")
    pip_line = f"# pip install {' '.join(sorted(set(pip_pkgs)))}"

    return "\n".join([
        '"""',
        f"  {app_name}",
        f"  {app_desc}",
        "  Generated by Pipesets AI",
        "",
        f"  {pip_line}",
        "",
        "  Environment variables:",
        *[f"    {k}=...  # {v}" for k, v in env_vars.items()],
        '"""',
        "",
        "import os",
        "from autogen import ConversableAgent, UserProxyAgent",
        "from autogen import register_function",
        "",
        f"os.environ.setdefault({json.dumps(env_key)}, {json.dumps(api_key_val)})",
        "",
        "# ── Tool Functions ────────────────────────────────────────────────────────────",
        *[line for block in tool_funcs for line in block.splitlines()],
        "",
        "# ── LLM Config ───────────────────────────────────────────────────────────────",
        "llm_config = {",
        '    "config_list": [{',
        f'        "model": {json.dumps(model)},',
        f'        "api_key": os.environ.get({json.dumps(env_key)}, ""),',
        "    }],",
        f'    "temperature": {temperature},',
        f'    "max_tokens": {max_tokens},',
        "}",
        "",
        "# ── Agents ───────────────────────────────────────────────────────────────────",
        "assistant = ConversableAgent(",
        f'    name={json.dumps(app_name.replace(" ", "_") + "_assistant")!r},',
        f'    system_message={json.dumps(system_prompt)},',
        "    llm_config=llm_config,",
        ")",
        "",
        "user_proxy = UserProxyAgent(",
        '    name="user_proxy",',
        '    human_input_mode="NEVER",',
        "    max_consecutive_auto_reply=10,",
        '    code_execution_config={"work_dir": "coding", "use_docker": False},',
        ")",
        "",
        "# ── Register Tools ────────────────────────────────────────────────────────────",
        *tool_registrations,
        "",
        'if __name__ == "__main__":',
        '    user_proxy.initiate_chat(assistant, message="Hello, what can you do?")',
    ])
